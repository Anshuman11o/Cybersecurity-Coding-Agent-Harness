/** Language of a dependency manifest whose extension says nothing (requirements.txt, go.mod, Gemfile). */
export const MANIFEST_LANGUAGE = 'manifest'

/**
 * Dependency manifests, by lower-cased basename. Inventoried whatever their
 * extension; a manifest with a known extension (package.json, pom.xml,
 * Cargo.toml) keeps that extension's language, the rest are MANIFEST_LANGUAGE.
 */
const MANIFEST_BASENAMES = new Set([
  'package.json', 'composer.json', 'pyproject.toml', 'cargo.toml', 'pom.xml',
  'pubspec.yaml', 'package.swift',
  'requirements.txt', 'pipfile', 'setup.cfg', 'gemfile', 'go.mod',
  'build.gradle', 'build.gradle.kts', 'settings.gradle', 'settings.gradle.kts',
  'packages.config', 'mix.exs', 'deps.edn', 'project.clj', 'build.sbt',
])

/** requirements-dev.txt, requirements_test.txt, requirements.in, requirements/base.txt */
function isRequirementsFile(lowerRel: string, lowerBase: string): boolean {
  if (/^requirements([-_.][\w.-]+)?\.(txt|in)$/.test(lowerBase)) return true
  return /(^|\/)requirements\/[^/]+\.(txt|in)$/.test(lowerRel)
}

/** Lockfiles, by lower-cased basename. Generated by a package manager; never inventoried. */
const LOCKFILE_BASENAMES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml',
  'bun.lockb', 'bun.lock', 'deno.lock',
  'pipfile.lock', 'poetry.lock', 'uv.lock', 'pdm.lock',
  'gemfile.lock', 'composer.lock', 'cargo.lock', 'go.sum', 'go.work.sum',
  'packages.lock.json', 'mix.lock', 'pubspec.lock', 'podfile.lock',
  'package.resolved', 'flake.lock', 'gradle.lockfile', 'conan.lock',
  '.terraform.lock.hcl',
])

function lowerParts(relPath: string): { lowerRel: string; lowerBase: string } {
  const lowerRel = relPath.split(path.sep).join('/').toLowerCase()
  return { lowerRel, lowerBase: lowerRel.slice(lowerRel.lastIndexOf('/') + 1) }
}

export function isDependencyManifest(relPath: string): boolean {
  const { lowerRel, lowerBase } = lowerParts(relPath)
  if (MANIFEST_BASENAMES.has(lowerBase)) return true
  if (lowerBase.endsWith('.csproj') || lowerBase.endsWith('.fsproj') || lowerBase.endsWith('.vbproj')) return true
  return isRequirementsFile(lowerRel, lowerBase)
}

export function isLockfile(relPath: string): boolean {
  return LOCKFILE_BASENAMES.has(lowerParts(relPath).lowerBase)
}

/**
 * The language of a target-relative path, or null when the scanner does not
 * read files of this kind (images, archives, markdown, plain text ...).
 * Lockfiles are not special-cased here; file selection excludes them first.
 */
export function languageForPath(relPath: string): string | null {
  const { lowerRel, lowerBase } = lowerParts(relPath)
  if (lowerBase === 'dockerfile' || lowerBase.startsWith('dockerfile.')) return 'docker'
  const ext = path.extname(lowerBase)
  // A manifest's own extension wins when it has one the table knows
  // (package.json stays json); build.gradle.kts is a manifest, not kotlin.
  if (isDependencyManifest(lowerRel)) {
    if (lowerBase.endsWith('.gradle.kts')) return MANIFEST_LANGUAGE
    return EXTENSION_LANGUAGES[ext] ?? MANIFEST_LANGUAGE
  }
  return EXTENSION_LANGUAGES[ext] ?? null
}

