/** One selected file. Every entry becomes exactly one lane in Stage 0.5. */
export interface InventoryEntry {
  /** Target-relative, forward slashes. */
  path: string
  /** From languageForPath(). */
  language: string
  /** On-disk size (fs.statSync). */
  bytes: number
  /** Matched a test directory or test file pattern (skipped by default). */
  test: boolean
  /** bytes > options.max_file_bytes; content is never read past the cap check. */
  oversize: boolean
  /** Zero bytes or whitespace only. */
  empty: boolean
}

/** Why a path never entered the inventory at all. */
export type ExclusionReason =
  | 'user-excluded'
  | 'gitignore'       // matched a .gitignore inside the target
  | 'secscanignore'   // matched the target's .secscanignore
  | 'vendor_dir'      // node_modules, vendor, venv (any dir holding pyvenv.cfg), ...
  | 'build_dir'       // dist, build, out, coverage, .next, ...
  | 'tool_dir'        // .git, .hg, .svn, .secscan, ...
  | 'lockfile'        // isLockfile()
  | 'minified'        // *.min.js or minified by content
  | 'generated'       // generated-code header or generated-file name pattern
  | 'symlink'         // symlinks are never followed or inventoried

export interface ExclusionGroup {
  reason: ExclusionReason
  /** Directories excluded whole and not walked, target-relative with a trailing '/'. Sorted. */
  dirs: string[]
  /** Files excluded individually, target-relative. Sorted. */
  files: string[]
}

export interface SelectionOptions {
  /** Per-file byte cap. Larger files are inventoried with oversize: true and get a skip lane. */
  max_file_bytes: number
  /** When false (the default), test files are inventoried with test: true and get a skip lane. */
  include_tests: boolean
}

export interface FileInventoryArtifact {
  schema_version: 1
  generated_at: string
  /** Absolute, symlink-resolved; the run context's target root. */
  target_dir: string
  options: SelectionOptions
  /** Target-relative paths of the ignore files that were honoured. Sorted. */
  ignore_files: string[]
  /** Sorted by path. */
  files: InventoryEntry[]
  /** Selected nonoversize source and root README paths admitted for guarded reads. */
  read_files?: string[]
  /** One group per reason that excluded anything, sorted by reason. */
  excluded: ExclusionGroup[]
  /** Files with no language (images, markdown, ...): counted, never listed. */
  unsupported: { count: number; by_extension: Record<string, number> }
  totals: {
    inventoried: number
    test: number
    oversize: number
    empty: number
    excluded_files: number
    excluded_dirs: number
  }
}

/** Implemented by file-selection.ts. */
export type SelectFiles = (targetDir: string, options?: Partial<SelectionOptions>) => FileInventoryArtifact

// ---------------------------------------------------------------------------
// symbols.json — the tree-sitter symbol table
// ---------------------------------------------------------------------------

export type SymbolKind =
  | 'function' | 'method' | 'class' | 'interface' | 'type' | 'enum'
  | 'struct' | 'trait' | 'module' | 'variable' | 'constant'

export interface SymbolEntry {
  name: string
  kind: SymbolKind
  /** 1-based, inclusive. */
  line: number
  end_line: number
  /** Visible outside its file by the language's own rule (export, pub, public, capitalised, ...). */
  exported: boolean
  /** Enclosing class / impl / module name for methods and nested types. */
  container?: string
}

export interface ImportEntry {
  /** Module, package or path as written (`express`, `./lib/insecurity`, `java.util.List`). */
  source: string
  /** Names bound by the import, when the syntax names them. */
  names: string[]
  line: number
}

export interface FileSymbols {
  language: string
  /** tree-sitter-wasms grammar name, e.g. 'tsx', 'c_sharp'. */
  grammar: string
  symbols: SymbolEntry[]
  imports: ImportEntry[]
  /** The tree contained ERROR or MISSING nodes; what could be read is still listed. */
  parse_error: boolean
}

export interface SymbolTableArtifact {
  schema_version: 1
  generated_at: string
  target_dir: string
  parser: { runtime: string; grammars: string }
  /** Files parsed, per language. */
  languages: Record<string, number>
  /** Inventory files not parsed, per reason (unsupported_language, test, oversize, empty, guard_denied, read_error). */
  skipped: Record<string, number>
  /** Keyed by target-relative path; keys sorted. */
  files: Record<string, FileSymbols>
}

/** Implemented by symbols.ts. */
export type ExtractSymbolTable = (
  targetDir: string,
  entries: readonly InventoryEntry[],
) => Promise<SymbolTableArtifact>

/**
 * Kinds that exist only at compile time. A route registration or an auto-CRUD
 * model can never name one, and matching on them gave data/types.ts eighteen
 * routes it does not serve, because its interfaces share the models' names.
 */
const TYPE_ONLY_KINDS: ReadonlySet<SymbolKind> = new Set(['interface', 'type'])

/** Runtime names a file makes visible to other files, per the symbol table. */
export function exportedNames(file: FileSymbols | undefined): Set<string> {
  const out = new Set<string>()
  for (const s of file?.symbols ?? []) if (s.exported && !TYPE_ONLY_KINDS.has(s.kind)) out.add(s.name)
  return out
}

