export interface AuthMechanism {
  /** What it is, in the model's words ("JWT bearer token check"). */
  name: string
  kind: 'authentication' | 'authorization' | 'session' | 'api_key' | 'oauth' | 'other'
  /** The code identifiers that apply it, exactly as call sites spell them (`security.isAuthorized`, `login_required`). */
  identifiers: string[]
  /** The subset of `identifiers` confirmed to exist in the symbol table or the route table. Only these tag routes. */
  verified_identifiers: string[]
  /** Inventory paths that define it. */
  defined_in: string[]
  /** Routes, path prefixes or files the model believes it guards. */
  protects: string[]
  evidence: string
}

export interface ArchitectureInfo {
  /** 'llm' when the model answered and its JSON parsed; 'deterministic' for the fallback (the stage is then degraded). */
  source: 'llm' | 'deterministic'
  model: string | null
  summary: string
  frameworks: { name: string; language: string | null; evidence: string }[]
  entry_points: { file: string; kind: string; description: string }[]
  auth_mechanisms: AuthMechanism[]
  data_stores: { name: string; kind: string; files: string[]; evidence: string }[]
  trust_boundaries: { name: string; description: string; files: string[] }[]
  /** Model output removed by validation: paths not in the inventory, identifiers that do not exist. */
  dropped: { field: string; value: string; reason: string }[]
}
