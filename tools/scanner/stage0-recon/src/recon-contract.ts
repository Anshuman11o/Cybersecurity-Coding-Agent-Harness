/**
 * Recon v3 contract: the shapes and tables Stage 0 and Stage 0.5 share.
 *
 * Written before the implementation (task 1b, productization plan §2.3) so the
 * parts built in parallel agree on one definition of each thing:
 *
 *   - what language a path is, and which paths are dependency manifests or
 *     lockfiles. Stage 0 and Stage 0.5 each used to carry their own extension
 *     table and their own directory exclusion list, and the two had drifted
 *     (Stage 0.5 knew .mjs, .c and .xml; Stage 0 did not). There is now one.
 *   - the artifacts Stage 0 writes for downstream stages: file-inventory.json
 *     (what was selected, what was excluded and why), symbols.json (the
 *     tree-sitter symbol table) and the `architecture` block of
 *     architecture-summary.json (the LLM's summary of the repo map).
 *
 * Zero runtime dependencies: Stage 0.5 and the Stage 2 analysis script import
 * the types and helpers below without pulling in Stage 0's parsers.
 */
