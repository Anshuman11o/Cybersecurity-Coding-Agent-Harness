/**
 * File selection: which files of a target the scanner reads, and a receipt for
 * every path it does not (recon v3, productization plan §2.3).
 *
 * Stage 0 and Stage 0.5 each used to walk the target with their own exclusion
 * list and their own extension table. The two drifted — Stage 0.5 knew .mjs and
 * .xml, Stage 0 did not — and Stage 0.5 papered over the gap with a second walk.
 * This is now the only walk: Stage 0 writes its result to file-inventory.json
 * and Stage 0.5 reads that instead of the disk.
 *
 * Ignore and user-scope rules are resolved before stat or content reads.
 * Built-in classifications for the exclusion receipt are:
 *
 *   symlink              never followed, never inventoried
 *   directory classes    tool_dir, vendor_dir, build_dir — by name, or (vendor)
 *                        a pyvenv.cfg inside; tool_dir also takes the run's
 *                        artifact root when it lies inside the target.
 *                        Recorded, not walked.
 *   lockfile             with or without a language (yarn.lock, go.sum ...)
 *   no language          counted in `unsupported`, never listed
 *   minified, generated
 *
 * Built-in name classes retain precedence in receipts so the reason recorded for
 * node_modules/ or package-lock.json does not depend on whether a repo happens
 * to list it in its .gitignore as well.
 *
 * Files that survive are inventoried with flags rather than removed — `test`,
 * `oversize` (content never read) and `empty` — and Stage 0.5 gives each a skip
 * lane with a stated reason, so they appear on the receipt instead of vanishing.
 */
import * as fs from 'node:fs'
import * as path from 'node:path'
import ignore from 'ignore'
import { PRODUCT_DIRNAME, getRunContext } from '../../shared/run-context.js'
import { auditReconRead } from '../../shared/read-guard.js'
import { compileGlob, normalizeScopePath } from '../../stage1-budget-governor/src/limits.js'
import {
  languageForPath, isLockfile,
  type ExclusionGroup, type ExclusionReason, type FileInventoryArtifact,
  type InventoryEntry, type SelectFiles, type SelectionOptions,
} from './recon-contract.js'

type Ignore = ReturnType<typeof ignore>

/** Semgrep's default target cap. */
export const DEFAULT_MAX_FILE_BYTES = 1_000_000

const SECSCANIGNORE = '.secscanignore'

// ---------------------------------------------------------------------------
// Directory classes, by exact name. Every name Stage 0 (EXCLUDED_DIRS) or
// Stage 0.5 (its supplemental walk) excluded before recon v3 is in one of these.
// ---------------------------------------------------------------------------

const TOOL_DIRS = new Set(['.git', '.hg', '.svn', PRODUCT_DIRNAME, '.qwen'])

const VENDOR_DIRS = new Set([
  'node_modules', 'bower_components', 'jspm_packages', 'vendor', 'third_party',
  '.venv', 'venv', 'virtualenv', 'site-packages', '__pycache__', '.tox', '.nox',
  '.eggs', '.bundle', 'Pods', 'Carthage', '.gradle', '.yarn', '.pnpm-store',
  '.mypy_cache', '.pytest_cache', '.ruff_cache',
])

const BUILD_DIRS = new Set([
  'dist', 'build', 'out', 'target', 'coverage', '.nyc_output', '.next', '.nuxt',
  '.output', '.angular', '.svelte-kit', '.parcel-cache', '.cache', '.turbo',
  '.vercel', '.serverless', '.terraform', 'storybook-static',
])

/** A virtualenv can have any name; its pyvenv.cfg is what identifies it. */
const VENV_MARKER = 'pyvenv.cfg'

// ---------------------------------------------------------------------------
// Test paths: flagged, not excluded (include_tests clears the flag)
// ---------------------------------------------------------------------------

const TEST_DIRS = new Set([
  'test', 'tests', '__tests__', '__test__', 'spec', 'specs', 'e2e', 'cypress',
  'testdata', '__mocks__', '__fixtures__',
])

// Case-sensitive on purpose: lower-casing would let *Test.java match Latest.java.
const TEST_FILE_PATTERNS: readonly RegExp[] = [
  /\.spec\./, /\.test\./, /_test\.go$/, /^test_.*\.py$/, /_test\.py$/,
  /Tests?\.java$/, /Test\.kt$/, /_spec\.rb$/, /_test\.rb$/, /Test\.php$/, /Tests?\.cs$/,
]

// ---------------------------------------------------------------------------
// Minified and generated files: excluded
// ---------------------------------------------------------------------------

// Matched against the lower-cased basename: Visual Studio writes Form1.Designer.cs.
const MINIFIED_NAME = /\.min\.(js|mjs|cjs|css)$|-min\.js$/
const GENERATED_NAMES: readonly RegExp[] = [
  /\.pb\.go$/, /_pb2\.py$/, /_pb2_grpc\.py$/, /\.pb\.(cc|h)$/, /\.g\.dart$/,
  /\.freezed\.dart$/, /\.designer\.cs$/, /\.g\.cs$/, /\.generated\./,
]

// Case-sensitive on purpose: a case-insensitive @generated would match JPA's
// @GeneratedValue, which sits near the top of hand-written entity classes.
const GENERATED_HEADER =
  /@generated|Code generated .* DO NOT EDIT|<auto-generated|This file (was|is) (automatically|auto-) ?generated|Generated by the protocol buffer compiler/
const GENERATED_HEADER_BYTES = 1024

const MINIFIED_LANGUAGES = new Set(['javascript', 'css'])
const MINIFIED_MIN_BYTES = 2048
const MINIFIED_LONGEST_LINE = 5000
const MINIFIED_MEAN_LINE = 250

// ---------------------------------------------------------------------------
// Options
// ---------------------------------------------------------------------------

function resolveOptions(options: Partial<SelectionOptions>): SelectionOptions {
  const max = options.max_file_bytes ?? DEFAULT_MAX_FILE_BYTES
  if (!Number.isSafeInteger(max) || max < 1) {
    throw new Error(`[file-selection] max_file_bytes must be a positive whole number, got ${max}`)
  }
  const includeTests = options.include_tests ?? false
  if (typeof includeTests !== 'boolean') {
    throw new Error(`[file-selection] include_tests must be a boolean, got ${String(includeTests)}`)
  }
  return { max_file_bytes: max, include_tests: includeTests }
}

/**
 * Selection options from the environment: SCANNER_MAX_FILE_BYTES (a positive
 * whole number of bytes) and SCANNER_INCLUDE_TESTS ('1' or '0'). The hook the
 * CLI flags set (task 1c). Unset or empty means the default; anything else
 * that does not parse throws, so a typo cannot silently scan with defaults.
 */
export function selectionOptionsFromEnv(
  env: Record<string, string | undefined> = process.env,
): SelectionOptions {
  let maxFileBytes = DEFAULT_MAX_FILE_BYTES
  const rawMax = env.SCANNER_MAX_FILE_BYTES
  if (rawMax !== undefined && rawMax !== '') {
    const n = Number(rawMax)
    if (!/^[1-9][0-9]*$/.test(rawMax) || !Number.isSafeInteger(n)) {
      throw new Error(`[file-selection] SCANNER_MAX_FILE_BYTES must be a positive whole number of bytes, got '${rawMax}'`)
    }
    maxFileBytes = n
  }

  let includeTests = false
  const rawTests = env.SCANNER_INCLUDE_TESTS
  if (rawTests !== undefined && rawTests !== '') {
    if (rawTests !== '1' && rawTests !== '0') {
      throw new Error(`[file-selection] SCANNER_INCLUDE_TESTS must be '1' or '0', got '${rawTests}'`)
    }
    includeTests = rawTests === '1'
  }

  return { max_file_bytes: maxFileBytes, include_tests: includeTests }
}

// ---------------------------------------------------------------------------
// Ignore files
// ---------------------------------------------------------------------------

interface IgnoreLayer {
  /** Target-relative directory the file's patterns are relative to; '' for the root. */
  base: string
  ig: Ignore
  reason: 'gitignore' | 'secscanignore'
  /** `ig` with a directory's ancestors re-included, keyed by that directory (see ignoredBy). */
  reincluded: Map<string, Ignore>
}

function ignoreLayer(base: string, ig: Ignore, reason: IgnoreLayer['reason']): IgnoreLayer {
  return { base, ig, reason, reincluded: new Map() }
}

/** True for a regular file; false for a symlink, a directory, or nothing readable. */
function isRegularFile(abs: string): boolean {
  try {
    return fs.lstatSync(abs, { throwIfNoEntry: false })?.isFile() ?? false
  } catch {
    return false
  }
}

/**
 * A regular file's patterns, or null. A symlinked ignore file is not followed;
 * one that cannot be read is not honoured, and is absent from ignore_files.
 */
function loadIgnoreFile(abs: string): Ignore | null {
  if (!isRegularFile(abs)) return null
  let text: string
  try {
    text = fs.readFileSync(abs, 'utf-8')
    auditReconRead(abs)
  } catch {
    return null
  }
  // Case-sensitive, as git is by default on a case-sensitive filesystem. The
  // library defaults to case-insensitive, which would make the same repo select
  // differently depending on the OS it is scanned on.
  return ignore({ ignorecase: false }).add(text)
}

/** A literal path as a gitignore pattern: backslash-escape every character the syntax gives a meaning. */
function escapePattern(literal: string): string {
  return literal.replace(/[\\*?[\]!#]/g, '\\$&')
}

/**
 * The layer's patterns with every ancestor directory of `dirSub` (layer-relative)
 * re-included by an appended anchored `!/dir/`. Those match only the exact
 * directories named, never a file or a deeper directory, so every other
 * verdict is the layer's own.
 */
function withAncestorsReincluded(layer: IgnoreLayer, dirSub: string): Ignore {
  let ig = layer.reincluded.get(dirSub)
  if (!ig) {
    const parts = dirSub.split('/')
    const negations = parts.map((_, i) => '!/' + escapePattern(parts.slice(0, i + 1).join('/')) + '/')
    ig = ignore({ ignorecase: false }).add(layer.ig).add(negations)
    layer.reincluded.set(dirSub, ig)
  }
  return ig
}

/**
 * Whether the ignore layers exclude a path, and which kind of file did it.
 * Layers run root -> deepest .gitignore -> .secscanignore; each one that
 * matches overrides the ones before, so a deeper `!pattern` re-includes.
 *
 * The walk only reaches a path whose ancestors are all not ignored, but one
 * layer can still ignore an ancestor that a later layer re-included (root
 * `gen/`, then `pkg/.gitignore` with `!gen/`). The library would report that
 * ancestor's verdict for everything beneath it and never test the path's own
 * patterns, so for that layer the path is tested with its ancestors
 * re-included — which is what git does.
 */
function ignoredBy(rel: string, isDir: boolean, layers: readonly IgnoreLayer[]): ExclusionReason | null {
  let reason: ExclusionReason | null = null
  for (const layer of layers) {
    const sub = layer.base ? rel.slice(layer.base.length + 1) : rel
    const slash = sub.lastIndexOf('/')
    let ig = layer.ig
    if (slash >= 0 && ig.test(sub.slice(0, slash + 1)).ignored) ig = withAncestorsReincluded(layer, sub.slice(0, slash))
    const r = ig.test(isDir ? sub + '/' : sub)
    if (r.ignored) reason = layer.reason
    else if (r.unignored) reason = null
  }
  return reason
}

// ---------------------------------------------------------------------------
// Per-file checks
// ---------------------------------------------------------------------------

function isTestPath(rel: string): boolean {
  const parts = rel.split('/')
  const base = parts.pop()!
  return parts.some((p) => TEST_DIRS.has(p)) || TEST_FILE_PATTERNS.some((re) => re.test(base))
}

/** Longest line over 5,000 characters and mean line length over 250. */
function looksMinified(text: string): boolean {
  let longest = 0
  let lines = 0
  let start = 0
  for (;;) {
    const nl = text.indexOf('\n', start)
    const end = nl < 0 ? text.length : nl
    if (end - start > longest) longest = end - start
    lines++
    if (nl < 0) break
    start = nl + 1
  }
  const mean = (text.length - (lines - 1)) / lines
  return longest > MINIFIED_LONGEST_LINE && mean > MINIFIED_MEAN_LINE
}

/**
 * Reads a file at most once, and only as far as a check needs. Returns null
 * for a file that cannot be read; the caller then leaves every content-based
 * verdict at "no" rather than guessing.
 */
function contentReader(abs: string) {
  let whole: Buffer | null | undefined
  let head: Buffer | null | undefined
  return {
    whole(): string | null {
      if (whole === undefined) {
        try { whole = fs.readFileSync(abs); auditReconRead(abs) } catch { whole = null }
      }
      return whole === null ? null : whole.toString('utf-8')
    },
    head(): string | null {
      if (whole) return whole.subarray(0, GENERATED_HEADER_BYTES).toString('utf-8')
      if (head === undefined) {
        try {
          const fd = fs.openSync(abs, 'r')
          try {
            const buf = Buffer.alloc(GENERATED_HEADER_BYTES)
            head = buf.subarray(0, fs.readSync(fd, buf, 0, buf.length, 0))
            auditReconRead(abs)
          } finally {
            fs.closeSync(fd)
          }
        } catch {
          head = null
        }
      }
      return head === null ? null : head.toString('utf-8')
    },
  }
}

